"""
Writes candidates.json for the agriculture domain.

GOIR rows are referenced by (order number, date) and their download URL is looked up in
ingest/incoming/_catalog/goir_agri.json, so no URL is typed by hand. Judgement (keep/skip,
reason, why, in_force) is written here; re-run after editing, then run collect.py.

Run:  python ingest/incoming/agriculture/build_candidates.py
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
CAT = json.loads((HERE.parent / "_catalog" / "goir_agri.json").read_text(encoding="utf-8"))
GOIR = {(r["number"], r["date"]): r for r in CAT["rows"]}
# agriculture.ap.gov.in document catalogue (catalog_agri.py), keyed by the file UUID
SITE_CAT = json.loads((HERE.parent / "_catalog" / "agri_site.json").read_text(encoding="utf-8"))
SITE = {r["url"].rsplit("/", 1)[-1]: r for r in SITE_CAT["rows"]}


def site(uuid, title, department="Agriculture & Cooperation", doc_type="other", **kw):
    """A file from the department's current site, agriculture.ap.gov.in."""
    r = SITE[uuid]
    return dict(title=title, department=department,
                group=f"agriculture.ap.gov.in: {r['compType']}" + (f" / {r['group']}" if r["group"] else ""),
                source_url=r["url"], source_page=r["source_page"], doc_type=doc_type,
                date=kw.pop("date", r["date"]), **kw)


def go(number, date, title, department, doc_type="go", **kw):
    r = GOIR[(number, date)]
    return dict(title=title, department=department,
                group=f"GOIR: {r['department']} / {r['section']}",
                source_url=r["url"], source_page="https://goir.ap.gov.in/",
                doc_type=doc_type, number=number, date=date, **kw)


